"""
Generates docs/DATA_DICTIONARY.md from the live database catalog, so the
data dictionary always matches the real schema.
Usage: python scripts/generate_data_dictionary.py "postgresql://user:pass@localhost:5432/resolvex"
(requires: pip install psycopg2-binary)
"""
import sys
from pathlib import Path
import psycopg2

PURPOSE = {
    "roles": "Lookup of the four application roles used for role based access control.",
    "users": "Every person who can log in. Passwords are stored only as bcrypt hashes.",
    "technicians": "Specialisation (ISA) of users with the TECHNICIAN role: rate, job limit, availability.",
    "technician_skills": "M:N between technicians and asset categories, with a skill level.",
    "buildings": "Campus buildings with an importance level used in priority scoring.",
    "rooms": "Rooms / areas inside a building (unique room number per building).",
    "asset_categories": "Kinds of infrastructure; also the incident category and technician skill area.",
    "assets": "Registered equipment (AC units, lifts, projectors...) located in a room.",
    "sla_policies": "Priority levels P1-P4 with the score threshold and response / resolution targets.",
    "incident_status_transitions": "Allowed incident state changes (data-driven state machine).",
    "incidents": "Reported infrastructure problems. Priority, level and SLA deadline are computed by trigger.",
    "incident_embeddings": "Vector store: 384-d sentence embedding of each incident (pgvector).",
    "incident_reporters": "Users who confirmed an existing incident ('me too'), M:N users-incidents.",
    "incident_status_history": "Timeline of every status change, written by trigger.",
    "work_orders": "Assignment of an incident to a technician and the repair carried out.",
    "spare_parts": "Inventory of spare parts with stock and reorder level.",
    "work_order_parts": "M:N between work orders and spare parts with quantity and price at use.",
    "maintenance_records": "Cost record per repair / preventive service of an asset.",
    "alerts": "Notifications generated by triggers and procedures.",
    "audit_log": "Generic row-level audit trail (JSONB before / after).",
}

conn = psycopg2.connect(sys.argv[1])
cur = conn.cursor()
cur.execute("""SELECT table_name FROM information_schema.tables
               WHERE table_schema='public' AND table_type='BASE TABLE'""")
tables = [r[0] for r in cur.fetchall()]
order = list(PURPOSE)
tables.sort(key=lambda t: order.index(t) if t in order else 99)

cur.execute("""
SELECT tc.table_name, kcu.column_name, tc.constraint_type, tc.constraint_name,
       ccu.table_name AS ref_table, ccu.column_name AS ref_col
  FROM information_schema.table_constraints tc
  JOIN information_schema.key_column_usage kcu
    ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema
  LEFT JOIN information_schema.constraint_column_usage ccu
    ON ccu.constraint_name = tc.constraint_name AND tc.constraint_type = 'FOREIGN KEY'
 WHERE tc.table_schema = 'public' AND tc.constraint_type IN ('PRIMARY KEY','FOREIGN KEY','UNIQUE')""")
keys = {}
for t, c, typ, name, rt, rc in cur.fetchall():
    tag = {"PRIMARY KEY": "PK", "UNIQUE": "UQ"}.get(typ) or f"FK -> {rt}({rc})"
    keys.setdefault((t, c), [])
    if tag not in keys[(t, c)]:
        keys[(t, c)].append(tag)

cur.execute("""
SELECT rel.relname, con.conname, pg_get_constraintdef(con.oid)
  FROM pg_constraint con JOIN pg_class rel ON rel.oid = con.conrelid
  JOIN pg_namespace n ON n.oid = rel.relnamespace
 WHERE n.nspname = 'public' AND con.contype = 'c' ORDER BY rel.relname, con.conname""")
checks = {}
for t, name, d in cur.fetchall():
    checks.setdefault(t, []).append((name, d))

out = ["# Data dictionary", "",
       "Generated from the live PostgreSQL catalog by `scripts/generate_data_dictionary.py`.",
       "Key: PK primary key, FK foreign key, UQ unique, NN not null.", ""]
for t in tables:
    out += [f"## {t}", "", PURPOSE.get(t, ""), "",
            "| Column | Type | Null | Default | Keys |", "|---|---|---|---|---|"]
    cur.execute("""SELECT column_name, CASE WHEN data_type='USER-DEFINED' THEN udt_name ELSE data_type END,
                          character_maximum_length, numeric_precision, numeric_scale, is_nullable, column_default,
                          is_generated, generation_expression
                     FROM information_schema.columns WHERE table_schema='public' AND table_name=%s
                    ORDER BY ordinal_position""", (t,))
    for col, typ, ln, prec, scale, nul, default, gen, genexpr in cur.fetchall():
        if typ == "character varying": typ = f"varchar({ln})"
        elif typ == "character": typ = f"char({ln})"
        elif typ == "numeric" and prec: typ = f"numeric({prec},{scale})"
        elif typ == "vector": typ = "vector(384)"
        elif typ == "timestamp with time zone": typ = "timestamptz"
        d = (default or "").replace("|", "/")
        if d.startswith("nextval"): d = "serial"
        if gen == "ALWAYS": d = "GENERATED"
        out.append(f"| {col} | {typ} | {'NN' if nul == 'NO' else ''} | {d[:40]} | {', '.join(keys.get((t, col), []))} |")
    if checks.get(t):
        out += ["", "CHECK constraints:", ""]
        for name, d in checks[t]:
            out.append(f"- `{name}`: `{d.replace('|', '/')[:220]}`")
    out.append("")
Path(__file__).resolve().parent.parent.joinpath("docs", "DATA_DICTIONARY.md").write_text("\n".join(out))
print("wrote docs/DATA_DICTIONARY.md")
